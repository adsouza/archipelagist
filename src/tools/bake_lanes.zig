// Writes src/core/ferry_lanes.zig from the geography. Run it after changing an
// island's grid, harbor, or position:
//   zig build bake-lanes
const std = @import("std");
const colony = @import("core").colony;

pub fn main(process: std.process.Init) !void {
    var out: std.Io.Writer.Allocating = .init(process.gpa);
    defer out.deinit();
    const w = &out.writer;
    try w.writeAll(
        \\// Generated by `zig build bake-lanes` from ferry.computeLane. Do not edit.
        \\// Pairs of harbors the ferry can sail between directly, in both directions,
        \\// with the course that stays at sea: an index into ferry.course_bends, or
        \\// waypoints in chart units when no bend clears the land.
        \\pub const Lane = struct { from: u8, to: u8, bend: u8 = 0, waypoints: []const [2]f32 = &.{} };
        \\
        \\pub const lanes = [_]Lane{
        \\
    );
    for (0..colony.settlement_count) |from| {
        for (from + 1..colony.settlement_count) |to| {
            const plan = colony.ferry.computeLane(from, to) orelse continue;
            try w.print("    .{{ .from = {d}, .to = {d}", .{ from, to });
            if (plan.bend != 0) try w.print(", .bend = {d}", .{plan.bend});
            if (plan.len > 0) {
                try w.writeAll(", .waypoints = &.{");
                for (plan.waypoints(), 0..) |point, i| try w.print("{s} .{{ {d:.2}, {d:.2} }}", .{ if (i == 0) "" else ",", point[0], point[1] });
                try w.writeAll(" }");
            }
            try w.print(" }}, // {s} and {s}\n", .{ colony.geography.names[from], colony.geography.names[to] });
        }
    }
    try w.writeAll("};\n");
    const args = try process.minimal.args.toSlice(process.arena.allocator());
    const path = if (args.len > 1) args[1] else "src/core/ferry_lanes.zig";
    try std.Io.Dir.cwd().writeFile(process.io, .{ .sub_path = path, .data = out.written() });
}
