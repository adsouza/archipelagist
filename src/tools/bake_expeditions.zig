// Bake direct sea passages using existing offshore waypoints and harbor approaches.
const std = @import("std");
const colony = @import("core").colony;
const ferry = colony.ferry;
const Point = ferry.Point;
const ports = colony.settlement_count;
const no_port = ports;
const speed = colony.ocean.direct_speed;
const limit = speed * colony.ocean.barque_leg_limit;
const infinity = std.math.inf(f32);

fn distance(a: Point, b: Point) f32 {
    return @sqrt((a[0] - b[0]) * (a[0] - b[0]) + (a[1] - b[1]) * (a[1] - b[1]));
}

fn addOffshore(points: *std.ArrayList(Point), gpa: std.mem.Allocator, point: Point) !void {
    for (points.items) |existing| {
        if (distance(existing, point) < 0.1) return;
    }
    if (!ferry.onLand(point, no_port, no_port)) try points.append(gpa, point);
}

pub fn main(process: std.process.Init) !void {
    const gpa = process.arena.allocator();
    var points: std.ArrayList(Point) = .empty;
    for (0..ports) |port| try points.append(gpa, ferry.berth(port));
    for (colony.geography.sites.all) |site| {
        for (site.waypoints[0 .. site.waypoints.len - 1]) |point| try addOffshore(&points, gpa, point);
    }
    for ([_]Point{
        .{ 720, 590 },  .{ 900, 620 },    .{ 1040, 560 }, .{ 1365, 486 }, .{ 1367, 195 },  .{ 1320, 65 },
        .{ -240, 481 }, .{ -1175, -560 }, .{ 1740, 478 }, .{ 1700, 170 }, .{ 1540, -465 },
    }) |point| try addOffshore(&points, gpa, point);
    for (0..ports) |port| {
        const berth = ferry.berth(port);
        const offset = ferry.dockOffset(port);
        const length = distance(.{ 0, 0 }, offset);
        for ([_]f32{ 24, 48 }) |reach| {
            try addOffshore(&points, gpa, .{ berth[0] + reach * offset[0] / length, berth[1] + reach * offset[1] / length });
        }
        for (ferry.neighbors(port).slice()) |neighbor| {
            if (neighbor <= port) continue;
            for ([_]f32{ 0.2, 0.5, 0.8 }) |t| try addOffshore(&points, gpa, ferry.coursePosition(port, neighbor, t));
        }
    }

    const n = points.items.len;
    std.debug.print("Checking visibility between {d} points at sea and at harbors\n", .{n});
    const lengths = try gpa.alloc(f32, n * n);
    @memset(lengths, infinity);
    for (points.items, 0..) |point, from| {
        for (from + 1..n) |to| {
            const run = distance(point, points.items[to]);
            if (run > limit) continue;
            const source = if (from < ports) from else no_port;
            const target = if (to < ports) to else no_port;
            if (!ferry.segmentClear(point, points.items[to], source, target)) continue;
            lengths[from * n + to] = run;
            lengths[to * n + from] = run;
        }
    }

    var out: std.Io.Writer.Allocating = .init(gpa);
    const w = &out.writer;
    try w.writeAll(
        \\// Generated by zig build bake-expeditions. Routes use open water between
        \\// the listed harbors without calling at intermediate ports.
        \\pub const Passage = struct { from: u8, to: u8, seconds: u8, waypoints: []const [2]f32 = &.{} };
        \\pub const passages = [_]Passage{
        \\
    );
    const costs = try gpa.alloc(f32, n);
    const previous = try gpa.alloc(usize, n);
    const visited = try gpa.alloc(bool, n);
    const trail = try gpa.alloc(usize, n);
    for (1..ports) |source| {
        @memset(costs, infinity);
        @memset(visited, false);
        costs[source] = 0;
        previous[source] = source;
        while (true) {
            var best: ?usize = null;
            var shortest = infinity;
            for (costs, visited, 0..) |cost, done, i| {
                if (!done and cost < shortest) {
                    best = i;
                    shortest = cost;
                }
            }
            const at = best orelse break;
            visited[at] = true;
            // Harbors are endpoints. Passing through one would be a stopover.
            if (at < ports and at != source) continue;
            for (lengths[at * n ..][0..n], 0..) |run, to| {
                const made = shortest + run;
                if (made >= costs[to] or made > limit) continue;
                costs[to] = made;
                previous[to] = at;
            }
        }
        for (source + 1..ports) |to| {
            if (!std.math.isFinite(costs[to])) continue;
            const seconds: u8 = @intFromFloat(@max(3, @ceil(costs[to] / speed)));
            var count: usize = 0;
            var at = previous[to];
            while (at != source) : (at = previous[at]) {
                trail[count] = at;
                count += 1;
            }
            std.mem.reverse(usize, trail[0..count]);
            try w.print("    .{{ .from = {d}, .to = {d}, .seconds = {d}", .{ source, to, seconds });
            if (count != 0) {
                try w.writeAll(if (count == 1) ", .waypoints = &.{" else ", .waypoints = &.{ ");
                for (trail[0..count], 0..) |index, step| {
                    const point = points.items[index];
                    if (step != 0) try w.writeAll(", ");
                    try w.print(".{{ {d}, {d} }}", .{ point[0], point[1] });
                }
                try w.writeAll(if (count == 1) "}" else " }");
            }
            try w.print(" }}, // {s} to {s}\n", .{ colony.chart_names[source], colony.chart_names[to] });
        }
    }
    try w.writeAll("};\n");
    const args = try process.minimal.args.toSlice(gpa);
    const path = if (args.len > 1) args[1] else "src/core/expedition_routes.zig";
    try std.Io.Dir.cwd().writeFile(process.io, .{ .sub_path = path, .data = out.written() });
}
